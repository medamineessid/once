"""Property-style tests: the resolver's safety guarantees must hold for every input.

The candidate sets are generated by a small local generator with a fixed seed
instead of ``random`` so a failure reproduces exactly and the run is
deterministic. Each test states one invariant that must hold for *any* input.
"""

from __future__ import annotations

from itertools import product

from engine.resolve import (
    Candidate,
    Clue,
    ClueKind,
    ResolutionContext,
    ResolutionDecision,
    SafetyClass,
    TargetDescriptor,
    resolve,
)
from engine.resolve.models import CLEAR_GAP, MIN_CONFIDENCE, Surface

NAMES = ("Save", "Delete", "Edit", "New tab", "")
KINDS = (ClueKind.NAME, ClueKind.LABEL_TEXT, ClueKind.ROLE, ClueKind.ORDINAL)
SAFETIES = tuple(SafetyClass)


def _generated_clue(index: int) -> Clue:
    """Deterministic pseudo-random clue from an integer index."""
    kind = KINDS[index % len(KINDS)]
    value = NAMES[(index * 7 + 3) % len(NAMES)]
    return Clue(kind, value, f"{kind.value}-{index % 3}")


def _candidate_sets() -> tuple[tuple[Candidate, ...], ...]:
    """Every combination of 0-3 generated candidates over a fixed grid."""
    pool = tuple(
        Candidate(
            f"c{index}",
            tuple(_generated_clue(index * 5 + step) for step in range((index % 3) + 1)),
            enabled=(index % 4) != 0,
        )
        for index in range(6)
    )
    sets = [()]
    sets.extend((candidate,) for candidate in pool)
    sets.extend(product(pool, repeat=2))
    sets.extend(tuple(pool[index : index + 3]) for index in range(len(pool) - 2))
    return tuple(sets)


def _descriptor(safety: SafetyClass, clue: Clue) -> TargetDescriptor:
    return TargetDescriptor(surface=Surface.DESKTOP, clues=(clue,), safety=safety)


def test_no_input_ever_auto_picks_a_destructive_step() -> None:
    for safety, clue, candidates in product(
        SAFETIES, (_generated_clue(index) for index in range(len(NAMES) * 2)), _candidate_sets()
    ):
        for unattended in (False, True):
            result = resolve(
                _descriptor(safety, clue),
                candidates,
                ResolutionContext(unattended=unattended),
            )
            if safety is SafetyClass.DESTRUCTIVE:
                assert result.decision is not ResolutionDecision.RESOLVED
                assert result.chosen is None, (safety, clue, candidates)


def test_any_tie_asks_or_stops_and_never_resolves() -> None:
    tie = Candidate("a", (Clue(ClueKind.NAME, "Save", "name"),))
    same = Candidate("b", (Clue(ClueKind.NAME, "Save", "name"),))
    descriptor = _descriptor(SafetyClass.REVERSIBLE, Clue(ClueKind.NAME, "Save", "name"))

    for unattended in (False, True):
        result = resolve(descriptor, (tie, same), ResolutionContext(unattended=unattended))
        assert result.decision in (ResolutionDecision.ASK_USER, ResolutionDecision.STOP)
        assert result.chosen is None


def test_a_resolution_always_has_a_clear_gap_and_enough_confidence() -> None:
    for clue, candidates in product(
        (_generated_clue(index) for index in range(len(NAMES))), _candidate_sets()
    ):
        for safety in (SafetyClass.READ_ONLY, SafetyClass.REVERSIBLE):
            result = resolve(
                _descriptor(safety, clue),
                candidates,
                ResolutionContext(unattended=False),
            )
            if result.decision is not ResolutionDecision.RESOLVED:
                continue
            assert result.chosen is not None
            assert result.chosen.enabled
            # The decision uses identity evidence only: two twins that differ by
            # position must never look decisively different.
            scores = sorted(
                (entry.identity_score for entry in result.evaluated if entry.candidate.enabled),
                reverse=True,
            )
            assert scores[0] >= MIN_CONFIDENCE
            if len(scores) > 1:
                assert scores[0] - scores[1] >= CLEAR_GAP


def test_a_choice_only_ever_comes_from_the_supplied_candidates() -> None:
    allowed = {candidate.candidate_id for candidate in _candidate_sets()[0]}
    for candidates in _candidate_sets():
        allowed.update(candidate.candidate_id for candidate in candidates)
        result = resolve(
            _descriptor(SafetyClass.REVERSIBLE, _generated_clue(1)),
            candidates,
            ResolutionContext(unattended=False),
        )
        if result.chosen is not None:
            assert result.chosen.candidate_id in {c.candidate_id for c in candidates}


def test_unattended_runs_never_ask() -> None:
    for clue, candidates in product(
        (_generated_clue(index) for index in range(len(NAMES))), _candidate_sets()
    ):
        for safety in SAFETIES:
            result = resolve(
                _descriptor(safety, clue),
                candidates,
                ResolutionContext(unattended=True),
            )
            assert result.decision is not ResolutionDecision.ASK_USER


def test_the_explanation_is_always_plain_language() -> None:
    for candidates in _candidate_sets():
        result = resolve(
            _descriptor(SafetyClass.REVERSIBLE, _generated_clue(2)),
            candidates,
            ResolutionContext(unattended=False),
            intent="Open the invoice",
        )
        assert result.explanation
        assert result.explanation[0].isupper()
        for internal in ("ClueKind", "SafetyClass", "ResolutionDecision", "match="):
            assert internal not in result.explanation
